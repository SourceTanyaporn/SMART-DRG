// Helper functions for easy consumption
export function getAssessmentById(id) {
  return assessmentForms.find((f) => f.id === id);
}

export function getAssessmentsByCategory(category) {
  if (!category || category === "ทั้งหมด") return assessmentForms;
  return assessmentForms.filter((f) => f.category === category);
}
